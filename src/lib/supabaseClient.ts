
import { createClient } from '@supabase/supabase-js';
import type { Database } from './database.types'; // Will be generated by Supabase CLI

// البيئة المتغيرة لـ Supabase URL و Anon Key
// تأكد من إنشاء ملف .env.local في جذر المشروع وإضافة هذه المتغيرات إليه:
// NEXT_PUBLIC_SUPABASE_URL=your_supabase_url
// NEXT_PUBLIC_SUPABASE_ANON_KEY=your_supabase_anon_key

function sanitizeEnvValue(value?: string): string | undefined {
  if (!value) return undefined;
  const cleaned = value.trim().replace(/^[\["']+/, '').replace(/[\]"']+$/, '').trim();
  return cleaned || undefined;
}

function isValidHttpUrl(value?: string): value is string {
  if (!value) return false;
  try {
    const parsed = new URL(value);
    return parsed.protocol === 'http:' || parsed.protocol === 'https:';
  } catch {
    return false;
  }
}

const supabaseUrl = sanitizeEnvValue(process.env.NEXT_PUBLIC_SUPABASE_URL);
const supabaseAnonKey = sanitizeEnvValue(process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY);

const hasValidConfig = Boolean(
  supabaseUrl &&
  supabaseAnonKey &&
  isValidHttpUrl(supabaseUrl) &&
  !supabaseUrl.includes('your_supabase_url') &&
  !supabaseAnonKey.includes('your_supabase_anon_key')
);

function createTypedSupabaseClient() {
  return createClient<Database>(supabaseUrl!, supabaseAnonKey!);
}

export type TypedSupabaseClient = ReturnType<typeof createTypedSupabaseClient>;

let clientInstance: TypedSupabaseClient | null = null;
if (hasValidConfig) {
  try {
    clientInstance = createTypedSupabaseClient();
  } catch (error) {
    console.warn('[AI Studio] Failed to initialize Supabase client — falling back to mock store:', error);
    clientInstance = null;
  }
} else {
  console.warn('[AI Studio] Supabase env vars missing or invalid — using in-memory mock data store');
}

export const supabase: TypedSupabaseClient | null = clientInstance;
export const isSupabaseConfigured = Boolean(clientInstance);

