
import { createClient } from '@supabase/supabase-js';
import type { Database } from './database.types'; // Will be generated by Supabase CLI

// البيئة المتغيرة لـ Supabase URL و Anon Key
// تأكد من إنشاء ملف .env.local في جذر المشروع وإضافة هذه المتغيرات إليه:
// NEXT_PUBLIC_SUPABASE_URL=your_supabase_url
// NEXT_PUBLIC_SUPABASE_ANON_KEY=your_supabase_anon_key

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const supabaseAnonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

export const isSupabaseConfigured = Boolean(
  supabaseUrl &&
  supabaseAnonKey &&
  !supabaseUrl.includes('your_supabase_url') &&
  !supabaseAnonKey.includes('your_supabase_anon_key')
);

if (!isSupabaseConfigured) {
  console.warn('[AI Studio] Supabase env vars missing — using in-memory mock data store');
}

function createTypedSupabaseClient() {
  return createClient<Database>(supabaseUrl!, supabaseAnonKey!);
}

export type TypedSupabaseClient = ReturnType<typeof createTypedSupabaseClient>;

export const supabase: TypedSupabaseClient | null = isSupabaseConfigured
  ? createTypedSupabaseClient()
  : null;

